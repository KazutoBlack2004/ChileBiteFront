/**
 * Traduce una etiqueta cruda de MobileNet (ej. "Granny Smith" o "zucchini, courgette")
 * al nombre de ingrediente en español compatible con nuestra base de datos.
 *
 * @param {string} rawClassName - Etiqueta devuelta por MobileNet (`prediction.className`)
 * @returns {{ translated: string | null, matchedKey: string | null, originalLabel: string }}
 */
export function translateFoodLabel(rawClassName = "") {
  if (!rawClassName || typeof rawClassName !== "string") {
    return { translated: null, matchedKey: null, originalLabel: "" };
  }

  const originalLabel = rawClassName.trim();
  const normalizedFull = originalLabel.toLowerCase();

  // 1. Coincidencia exacta con toda la cadena
  if (FOOD_TRANSLATIONS[normalizedFull]) {
    return {
      translated: FOOD_TRANSLATIONS[normalizedFull],
      matchedKey: normalizedFull,
      originalLabel
    };
  }

  // 2. MobileNet suele separar sinónimos por comas (ej. "zucchini, courgette" o "pineapple, ananas")
  const segments = normalizedFull.split(",").map((s) => s.trim()).filter(Boolean);

  for (const segment of segments) {
    if (FOOD_TRANSLATIONS[segment]) {
      return {
        translated: FOOD_TRANSLATIONS[segment],
        matchedKey: segment,
        originalLabel
      };
    }
  }

  // 3. Coincidencia parcial por palabra completa dentro de los segmentos
  const sortedKeys = Object.keys(FOOD_TRANSLATIONS).sort((a, b) => b.length - a.length);
  for (const segment of segments) {
    for (const key of sortedKeys) {
      const escapedKey = key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      const regex = new RegExp(`\\b${escapedKey}\\b`, "i");
      if (regex.test(segment)) {
        return {
          translated: FOOD_TRANSLATIONS[key],
          matchedKey: key,
          originalLabel
        };
      }
    }
  }

  return {
    translated: null,
    matchedKey: null,
    originalLabel
  };
}
